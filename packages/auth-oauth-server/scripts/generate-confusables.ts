/**
 * Writes src/confusables-data.ts from the Unicode security data, for the
 * client name skeleton in src/client-name.ts. Run from the package directory:
 *
 *   npx tsx scripts/generate-confusables.ts && npx prettier --write src/confusables-data.ts
 *
 * The files are those published at
 * https://www.unicode.org/Public/security/17.0.0/confusables.txt and
 * https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt, read from the
 * unicodetools repository, which carries the same files.
 */
import { writeFileSync } from "node:fs"

const VERSION = "17.0.0"
const BASE =
  "https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data"
const CONFUSABLES_URL = `${BASE}/security/${VERSION}/confusables.txt`
const UNICODE_DATA_URL = `${BASE}/ucd/${VERSION}/UnicodeData.txt`

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  return response.text()
}

const mappings = new Map<string, string>()

// "13DF ;	0043 ;	MA	# ( Ꮯ → C ) ..." maps one code point to a sequence.
for (const line of (await fetchText(CONFUSABLES_URL)).split("\n")) {
  const match = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;/.exec(line)
  if (match) mappings.set(match[1]!, match[2]!.split(" ").join("+"))
}

// confusables.txt is case sensitive and leaves most small capitals alone, so
// `ᴄʟᴀᴜᴅᴇ` would not fold to `claude`. Map each Latin small capital to its
// lowercase letter, ahead of any confusables entry (which sends `ᴋ` to `ĸ`).
for (const line of (await fetchText(UNICODE_DATA_URL)).split("\n")) {
  const [code, name] = line.split(";")
  const letters = /^LATIN LETTER SMALL CAPITAL ([A-Z]{1,2})$/.exec(name ?? "")
  if (!code || !letters) continue
  mappings.set(
    code,
    Array.from(letters[1]!.toLowerCase(), (char) =>
      char.codePointAt(0)!.toString(16).toUpperCase().padStart(4, "0"),
    ).join("+"),
  )
}

const entries = [...mappings].map(([from, to]) => `${from}>${to}`)
const lines: string[] = []
for (let index = 0; index < entries.length; index += 8) {
  lines.push(`  "${entries.slice(index, index + 8).join(" ")}",`)
}

writeFileSync(
  new URL("../src/confusables-data.ts", import.meta.url),
  `// Generated by scripts/generate-confusables.ts from Unicode ${VERSION}
// confusables.txt and the Latin small capitals in UnicodeData.txt. Do not edit.
//
// Each entry is \`source>target\`: hex code points, with \`+\` joining a target
// sequence.
export const CONFUSABLES: readonly string[] = [
${lines.join("\n")}
]
`,
)
